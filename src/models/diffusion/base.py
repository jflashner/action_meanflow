"""
Logic shared by all next-frame generators (EDM, flow matching, MeanFlow, shortcut): the training loop over a
sequence of frames, GameNGen-style noise augmentation of the context frames, and self-forcing (training on
context frames generated by the model itself).
"""

from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple

import torch
from torch import Tensor
import torch.nn as nn

from data import Batch
from .inner_model import InnerModel
from utils import LossAndLogs


def add_dims(input: Tensor, n: int) -> Tensor:
    return input.reshape(input.shape + (1,) * (n - input.ndim))


def quantize(x: Tensor) -> Tensor:
    # Quantize to {0, ..., 255}, then back to [-1, 1]
    return x.clamp(-1, 1).add(1).div(2).mul(255).byte().div(255).mul(2).sub(1)


@dataclass
class SelfForcingConfig:
    prob: float = 0.0  # fraction of training samples whose context frames are generated by the model
    rollout_steps: int = 4  # number of frames generated (from ground-truth context) before the training target
    num_steps: int = 1  # sampling steps used to generate them
    start_after_steps: int = 0  # number of denoiser updates before self-forcing is switched on


class WorldModelDenoiser(nn.Module):
    """
    Subclasses implement `compute_loss` (one prediction step) and `make_sampler`.

    Their config must have the fields `inner_model`, `context_noise_max`, `context_noise_prob` and
    `context_noise_inference`.
    """

    def __init__(self, cfg: Any) -> None:
        super().__init__()
        self.cfg = cfg
        self.inner_model = InnerModel(cfg.inner_model)
        self.self_forcing: Optional[SelfForcingConfig] = None
        self.global_step = 0  # set by the trainer, used to delay self-forcing
        self._self_forcing_sampler = None

    @property
    def device(self) -> torch.device:
        return self.inner_model.noise_emb.weight.device

    @property
    def uses_context_noise(self) -> bool:
        return self.cfg.context_noise_max > 0

    def setup_self_forcing(self, cfg: Optional[SelfForcingConfig]) -> None:
        self.self_forcing = cfg if (cfg is not None and cfg.prob > 0) else None

    @property
    def num_extra_frames(self) -> int:
        """Frames needed in a training sequence on top of DIAMOND's (context + autoregressive steps)."""
        return 0 if self.self_forcing is None else self.self_forcing.rollout_steps

    # Context frames

    def augment_context(self, obs: Tensor, inference: bool = False) -> Tuple[Tensor, Optional[Tensor]]:
        """Noise augmentation of the (flattened) context frames, returns the noisy frames and the noise level."""
        if not self.uses_context_noise:
            return obs, None
        b = obs.size(0)
        if self.training and not inference:
            level = torch.rand(b, device=obs.device) * self.cfg.context_noise_max
            level = level * (torch.rand(b, device=obs.device) < self.cfg.context_noise_prob)
        else:
            level = torch.full((b,), self.cfg.context_noise_inference, device=obs.device)
        return obs + add_dims(level, obs.ndim) * torch.randn_like(obs), level

    @torch.no_grad()
    def generate_context(self, all_obs: Tensor, act: Tensor, num_rollout_steps: int) -> Tuple[Tensor, float]:
        """
        For a random subset of the batch, replace the frames that follow the ground-truth context by frames
        generated autoregressively with the model's own sampler (Self Forcing-style). Targets stay ground truth.
        """
        n = self.cfg.inner_model.num_steps_conditioning
        selected = torch.rand(all_obs.size(0), device=all_obs.device) < self.self_forcing.prob
        if not selected.any():
            return all_obs, 0.0
        if self._self_forcing_sampler is None:
            self._self_forcing_sampler = self.make_sampler(self.self_forcing.num_steps)
        obs = all_obs[selected]
        act = act[selected]
        for j in range(num_rollout_steps):
            obs[:, n + j], _ = self._self_forcing_sampler.sample(obs[:, j : n + j], act[:, j : n + j])
        all_obs = all_obs.clone()
        all_obs[selected] = obs
        return all_obs, selected.float().mean().item()

    # Training

    def forward(self, batch: Batch) -> LossAndLogs:
        n = self.cfg.inner_model.num_steps_conditioning
        all_obs = batch.obs.clone()
        logs: Dict[str, Any] = {}

        start = self.num_extra_frames
        if start > 0:
            if self.training and self.global_step >= self.self_forcing.start_after_steps:
                all_obs, frac = self.generate_context(all_obs, batch.act, start)
            else:
                frac = 0.0
            logs["self_forcing_frac"] = frac

        seq_length = all_obs.size(1) - n - start
        loss = 0

        for i in range(start, start + seq_length):
            obs = all_obs[:, i : n + i]
            next_obs = all_obs[:, n + i]
            act = batch.act[:, i : n + i]
            mask = batch.mask_padding[:, n + i]

            b, t, c, h, w = obs.shape
            obs = obs.reshape(b, t * c, h, w)
            obs, ctx_level = self.augment_context(obs)

            is_last = i == start + seq_length - 1
            loss_i, denoised, logs_i = self.compute_loss(next_obs, obs, act, mask, ctx_level, need_denoised=not is_last)
            loss += loss_i
            for k, v in logs_i.items():
                logs[k] = logs.get(k, 0) + v / seq_length

            if denoised is not None:
                all_obs[:, n + i] = denoised

        loss /= seq_length
        return loss, {"loss_denoising": loss.detach(), **logs}

    def compute_loss(
        self,
        next_obs: Tensor,
        obs: Tensor,
        act: Tensor,
        mask: Tensor,
        ctx_level: Optional[Tensor],
        need_denoised: bool,
    ) -> Tuple[Tensor, Optional[Tensor], Dict[str, Any]]:
        """Returns the loss, the (quantized) denoised next frame used as context for the next step, and logs."""
        raise NotImplementedError

    def make_sampler(self, num_steps: int):
        raise NotImplementedError


def masked_mean(x: Tensor, mask: Tensor) -> Tensor:
    return x[mask].mean() if mask.any() else x.sum() * 0


def extra_conds(*conds: Optional[Tensor]) -> List[Tensor]:
    return [c for c in conds if c is not None]
